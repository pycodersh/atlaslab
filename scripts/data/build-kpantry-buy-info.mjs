// Builds the K-Pantry "Where to Buy" review JSON and the data SQL from
// kpantry-buy-info.source.mjs + a dump of live pantry_ingredients rows.
//
//   node scripts/data/build-kpantry-buy-info.mjs <rows.json>
//
// rows.json: [{ id, name, name_ko, category, n (recipes using it), ess (as essential) }]
// Writes scripts/data/kpantry-buy-info.json and scripts/sql/kpantry-where-to-buy-02-data.sql.
import { readFileSync, writeFileSync } from 'node:fs'
import { BUY_INFO } from './kpantry-buy-info.source.mjs'

const UPDATED = '2026-11-17'
const rows = JSON.parse(readFileSync(process.argv[2], 'utf8'))
const linked = rows.filter(r => Number(r.n) > 0)
const orphans = rows.filter(r => Number(r.n) === 0)

const missing = linked.filter(r => !BUY_INFO[r.name]).map(r => r.name)
const extra = Object.keys(BUY_INFO).filter(n => !linked.some(r => r.name === n))
const slugs = Object.values(BUY_INFO).map(v => v.slug)
const dupSlugs = slugs.filter((s, i) => slugs.indexOf(s) !== i)
if (missing.length || extra.length || dupSlugs.length) {
  console.error({ missing, extra, dupSlugs })
  process.exit(1)
}

const out = linked
  .sort((a, b) => Number(b.n) - Number(a.n) || a.name.localeCompare(b.name))
  .map(r => {
    const { ko_fill, ...info } = BUY_INFO[r.name]
    return {
      id: r.id,
      name: r.name,
      name_ko: r.name_ko || null,
      ...(ko_fill && !r.name_ko ? { name_ko_proposed: ko_fill } : {}),
      recipe_count: Number(r.n),
      essential_in: Number(r.ess),
      ...info,
      buy_info_updated: UPDATED,
    }
  })

writeFileSync('scripts/data/kpantry-buy-info.json', JSON.stringify({
  generated: UPDATED,
  note: 'Recipe-linked ingredients only. Rows with 0 recipes are old seed duplicates and are left untouched.',
  orphans_not_filled: orphans.map(r => `${r.name} (${r.name_ko ?? ''})`),
  ingredients: out,
}, null, 2) + '\n')

const q = v => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`)
const cols = ['slug', 'romanized', 'store_level', 'price_tier', 'what_it_is', 'shopping_tip', 'label_hint', 'substitute', 'shelf_life', 'buy_query', 'weee_query']
const sql = [
  '-- TARGET: patto Supabase project — ref eecvvgkihtcgfikaimao',
  '-- K-Pantry "Where to Buy" data — generated by scripts/data/build-kpantry-buy-info.mjs',
  `-- ${out.length} recipe-linked ingredients. Only the new columns are written (plus name_ko where it was empty, if approved).`,
  'begin;',
  ...out.map(r => {
    const sets = cols.map(c => `${c} = ${q(r[c])}`)
    sets.push(`buy_info_updated = ${q(r.buy_info_updated)}`)
    if (r.name_ko_proposed) sets.push(`name_ko = coalesce(nullif(name_ko, ''), ${q(r.name_ko_proposed)})`)
    return `update public.pantry_ingredients set ${sets.join(', ')} where id = '${r.id}';`
  }),
  'commit;',
  '',
].join('\n')
writeFileSync('scripts/sql/kpantry-where-to-buy-02-data.sql', sql)

const lv = out.reduce((m, r) => ((m[r.store_level] = (m[r.store_level] ?? 0) + 1), m), {})
console.log(`ok: ${out.length} ingredients, orphans ${orphans.length}, store_level`, lv,
  'with buy_query', out.filter(r => r.buy_query).length, 'ko proposed', out.filter(r => r.name_ko_proposed).length)
