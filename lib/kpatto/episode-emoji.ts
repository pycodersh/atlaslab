/**
 * 에피소드 제목 → 상황 이모지 (Library 에피소드 헤더 카드용).
 * 1~4화는 지정값, 나머지는 제목 키워드로 고르고 못 찾으면 기본값을 쓴다.
 */
const EXPLICIT: Record<number, string> = {
  1: '☕',  // 카페에서
  2: '🚇', // 지하철에서
  3: '🍢', // 떡볶이 가게에서
  4: '🏪', // 편의점에서
}

// 위에서부터 처음 맞는 키워드
const KEYWORDS: Array<[RegExp, string]> = [
  [/카페/, '☕'],
  [/지하철/, '🚇'],
  [/떡볶이/, '🍢'],
  [/편의점/, '🏪'],
  [/노래방|K-POP/, '🎤'],
  [/댄스/, '💃'],
  [/시장/, '🛒'],
  [/뷰티/, '💄'],
  [/한강/, '🌉'],
  [/학교/, '🏫'],
  [/약속/, '📅'],
  [/길 잃은|여행|경복궁/, '🗺️'],
  [/드라마/, '📺'],
  [/날씨/, '⛅'],
  [/약국/, '💊'],
  [/병원/, '🏥'],
  [/취미/, '🎨'],
  [/건강|운동/, '💪'],
  [/어디 살/, '🏠'],
  [/SNS/, '📱'],
  [/음주/, '🍻'],
  [/배달/, '🛵'],
  [/패션/, '👗'],
  [/쇼핑/, '🛍️'],
  [/독서/, '📖'],
  [/직장|알바/, '💼'],
  [/분리수거|환경/, '♻️'],
  [/식당|맛집|음식|요리|밥/, '🍽️'],
  [/꿈|목표/, '🎯'],
  [/감사/, '🙏'],
  [/이별|그리움/, '🌧️'],
  [/위로|감정|감성/, '💗'],
  [/갈등|오해/, '⚡'],
  [/문화/, '🎎'],
  [/결심|계획/, '📝'],
]

export function episodeEmoji(epNum: number, title: string): string {
  if (EXPLICIT[epNum]) return EXPLICIT[epNum]
  for (const [re, emoji] of KEYWORDS) if (re.test(title)) return emoji
  return '💬'
}
