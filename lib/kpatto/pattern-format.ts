/**
 * 문법 패턴 표기 통일 (화면 표시용 — DB 의 korean 값은 건드리지 않는다).
 *
 *  - 앞뒤 하이픈 → 물결표:  -겠- → ~겠~ ,  -았/었- → ~았/었~ ,  -니? → ~니?
 *  - 모음 교체형 어미는 사전식 (으) 표기로:
 *      -으면서 → ~(으)면서 ,  -으면 안 되다 → ~(으)면 안 되다
 *      -을게 → ~(으)ㄹ게 ,  -은 지 → ~(으)ㄴ 지
 *    (-읍시다·-습니다 처럼 으로 시작하지 않는 것은 물결표만 바꾼다)
 *  이미 ~ 로 시작하는 패턴은 그대로 둔다.
 */
export function formatPatternTitle(korean: string): string {
  const k = (korean ?? '').trim()
  if (!k.startsWith('-')) return k
  let s = '~' + k.slice(1)
  s = s.replace(/-(?=\?|$)/, '~')               // 뒤쪽 하이픈(문장부호 앞 포함)
  s = s.replace(/^~으/, '~(으)')                  // -으면서 → ~(으)면서
  s = s.replace(/^~을/, '~(으)ㄹ')                // -을게 → ~(으)ㄹ게
  s = s.replace(/^~은/, '~(으)ㄴ')                // -은 지 → ~(으)ㄴ 지
  return s
}
